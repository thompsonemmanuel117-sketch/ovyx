import assert from 'node:assert/strict';
import fs from 'node:fs';
import { execFileSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';
import { buildAnnouncementEmail, emailPreferenceForCategory, escapeAnnouncementHtml, isEmailAddress, safeAnnouncementHref } from '../functions/api/_lib/announcement-delivery.js';
import { NOTIFICATION_DEFAULTS, normalizeNotificationPreferences } from '../functions/api/settings/preferences.js';
const read = path => fs.readFileSync(new URL('../' + path, import.meta.url), 'utf8');
for (const path of ['functions/api/_lib/announcement-delivery.js','functions/api/notifications.js','functions/api/admin/broadcasts.js','functions/api/_lib/admin-push.js','assets/ovyx-notifications.js','assets/ovyx-auth-welcome.js','assets/ovyx-admin-controls.js','sw.js']) execFileSync(process.execPath,['--check',fileURLToPath(new URL('../'+path,import.meta.url))],{stdio:'pipe'});
assert.equal(NOTIFICATION_DEFAULTS.pushAnnouncements,false);
assert.equal(normalizeNotificationPreferences({}).pushAnnouncements,false);
assert.equal(normalizeNotificationPreferences({pushAnnouncements:true}).pushAnnouncements,true);
assert.equal(normalizeNotificationPreferences({pushAnnouncements:'yes'}).pushAnnouncements,false);
assert.equal(emailPreferenceForCategory('security'),'emailSecurityAlerts');
assert.equal(emailPreferenceForCategory('account'),'emailSecurityAlerts');
assert.equal(emailPreferenceForCategory('product'),'emailProductUpdates');
assert.equal(isEmailAddress('amara@example.com'),true);
assert.equal(isEmailAddress('not-an-email'),false);
assert.match(escapeAnnouncementHtml('<img src=x onerror=alert(1)>'),/&lt;img/);
assert.doesNotMatch(escapeAnnouncementHtml('<script>alert(1)</script>'),/<script>/);
assert.equal(safeAnnouncementHref('/view-home','https://app.ovyx.example'),'https://app.ovyx.example/view-home');
assert.equal(safeAnnouncementHref('https://example.com/news','https://app.ovyx.example'),'https://example.com/news');
assert.equal(safeAnnouncementHref('javascript:alert(1)','https://app.ovyx.example'),'https://app.ovyx.example/');
assert.equal(safeAnnouncementHref('//evil.example/path','https://app.ovyx.example'),'https://app.ovyx.example/');
const email=buildAnnouncementEmail({origin:'https://app.ovyx.example',announcement:{title:'<Breaking news>',body:'First line\n<img src=x onerror=alert(1)>',link:'/view-home'},recipientName:'Amara <script>'});
assert.match(email.subject,/OVYX/);
assert.match(email.html,/\/assets\/ovyx-mark\.svg/);
assert.match(email.html,/&lt;Breaking news&gt;/);
assert.match(email.html,/&lt;script&gt;/);
assert.doesNotMatch(email.html,/<script>/);
assert.match(email.text,/https:\/\/app\.ovyx\.example\/view-home/);
